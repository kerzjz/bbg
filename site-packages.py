import subprocess
import sys

# 自动安装依赖下载工具
subprocess.run([sys.executable, "-m", "pip", "install", "pipreqs"], capture_output=True)

# 自动扫描你的代码，生成依赖列表
subprocess.run([sys.executable, "-m", "pipreqs", ".", "--force", "--encoding=utf-8"])

# 自动把所有依赖下载到当前文件夹的 site-packages 里
# ！！！这一步最关键！！！
subprocess.run([
    sys.executable, "-m", "pip", "install",
    "-r", "requirements.txt",
    "-t", "site-packages",  # 全部放进这里
    "--no-cache-dir",
    "--upgrade"
])

print("✅ 完成！所有依赖已自动下载到 site-packages 文件夹")